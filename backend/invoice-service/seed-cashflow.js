const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();
const crypto = require('crypto');

async function seedInvoices() {
  const businessId = '6f0e41ce-df82-4a5b-b6f6-2706bec7dbc2';
  
  // We need a clientId to associate these invoices with
  let clientId;
  const existingInvoice = await prisma.invoice.findFirst({ where: { businessId } });
  
  if (existingInvoice) {
    clientId = existingInvoice.clientId;
  } else {
    // Generate a dummy uuid for client
    clientId = crypto.randomUUID();
  }

  const invoices = [];
  const now = new Date();
  
  console.log(`Seeding invoices for business ${businessId} with client ${clientId}...`);

  // We want an upward trend overall but with some realistic variance
  // Let's generate data for the last 12 months
  let baseRevenue = 12000;
  
  for (let monthOffset = 11; monthOffset >= 0; monthOffset--) {
    const date = new Date(now.getFullYear(), now.getMonth() - monthOffset, 15); // Middle of the month
    
    // Upward trend: +5% to +10% per month, with some randomness
    const growthFactor = 1 + (Math.random() * 0.05 + 0.02);
    baseRevenue *= growthFactor;
    
    // 3 to 8 invoices per month
    const numInvoices = Math.floor(Math.random() * 6) + 3;
    
    for (let i = 0; i < numInvoices; i++) {
      // Fluctuate the individual invoice amounts
      const amount = (baseRevenue / numInvoices) * (0.8 + Math.random() * 0.4);
      
      const createdAt = new Date(date);
      createdAt.setDate(createdAt.getDate() + Math.floor(Math.random() * 10) - 5);
      
      const issueDate = new Date(createdAt);
      
      const dueDate = new Date(createdAt);
      dueDate.setDate(dueDate.getDate() + 30); // Net 30

      invoices.push({
        id: crypto.randomUUID(),
        businessId,
        clientId,
        invoiceNumber: `SEED-${date.getFullYear()}${(date.getMonth()+1).toString().padStart(2, '0')}-${i+1}`,
        status: 'PAID', // Most historical ones are paid
        issueDate,
        dueDate,
        totalAmount: parseFloat(amount.toFixed(2)),
        taxAmount: parseFloat((amount * 0.19).toFixed(2)),
        pdfUrl: 'seed_data.pdf',
        notes: 'Generated by AI seeding script to create a realistic cashflow history.',
        createdAt,
        updatedAt: createdAt
      });
    }
  }

  console.log(`Generated ${invoices.length} historical invoices.`);
  
  // Insert in batches
  let insertedCount = 0;
  for (let i = 0; i < invoices.length; i += 50) {
    const batch = invoices.slice(i, i + 50);
    const result = await prisma.invoice.createMany({
      data: batch,
      skipDuplicates: true,
    });
    insertedCount += result.count;
  }
  
  console.log(`✅ Successfully seeded ${insertedCount} realistic invoices into the database!`);
  await prisma.$disconnect();
}

seedInvoices().catch(e => {
  console.error(e);
  process.exit(1);
});

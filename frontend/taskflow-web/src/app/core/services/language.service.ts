@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly _language = signal<AppLanguage>('en');
  readonly language = this._language.asReadonly();
  readonly isArabic = computed(() => this._language() === 'ar');

  init(): void {
    const initial = this.getInitialLanguage();
    this.setLanguage(initial, false);
  }

  setLanguage(language: AppLanguage, persist = true): void {
    this._language.set(language);
    this.applyToDocument(language);

    if (persist && typeof localStorage !== 'undefined') {
      try {
        localStorage.setItem(STORAGE_KEY, language);
      } catch {}
    }
  }

  toggle(): void {
    this.setLanguage(this._language() === 'en' ? 'ar' : 'en');
  }

  translate(key: string, params?: Record<string, string | number>): string {
    const template = TRANSLATIONS[this._language()][key] ?? TRANSLATIONS.en[key] ?? key;

    if (!params) {
      return template;
    }

    return Object.entries(params).reduce((text, [paramKey, paramValue]) => {
      return text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
    }, template);
  }

  private getInitialLanguage(): AppLanguage {
    if (typeof window === 'undefined') return 'en';

    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'en' || saved === 'ar') return saved;
    } catch {}

    try {
      const browserLanguage = window.navigator.language?.toLowerCase() ?? 'en';
      return browserLanguage.startsWith('ar') ? 'ar' : 'en';
    } catch {
      return 'en';
    }
  }

  private applyToDocument(language: AppLanguage): void {
    if (typeof document === 'undefined') return;

    const root = document.documentElement;
    root.setAttribute('lang', language === 'ar' ? 'ar' : 'en');
    root.setAttribute('dir', language === 'ar' ? 'rtl' : 'ltr');
  }
}